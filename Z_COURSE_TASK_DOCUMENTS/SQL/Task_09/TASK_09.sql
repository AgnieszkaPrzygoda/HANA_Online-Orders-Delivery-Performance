-- Analyze Memory Usage
-- Overall memory usage
SELECT * FROM M_HOST_RESOURCE_UTILIZATION;

-- Memory usage by service
SELECT SERVICE_NAME,
       ROUND(TOTAL_MEMORY_USED_SIZE/1024/1024, 2) AS USED_MB,
       ROUND(PHYSICAL_MEMORY_SIZE/1024/1024, 2) AS ALLOCATED_MB
FROM M_SERVICE_MEMORY;

-- Top tables by memory usage
SELECT SCHEMA_NAME, TABLE_NAME,
       ROUND(MEMORY_SIZE_IN_TOTAL/1024/1024, 2) AS SIZE_MB,
       RECORD_COUNT
FROM M_CS_TABLES
ORDER BY MEMORY_SIZE_IN_TOTAL DESC
LIMIT 10;