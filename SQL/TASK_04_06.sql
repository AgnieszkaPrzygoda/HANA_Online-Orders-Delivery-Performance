-- Test 1: Basic star join output with all dimensions
SELECT
PRODUCT_NAME,
CATEGORY,
CUSTOMER_NAME,
REGION,
YEAR,
MONTH,
SUM(AMOUNT) AS TOTAL_SALES,
SUM(QUANTITY) AS TOTAL_QUANTITY
FROM "CAC_R_ORDERS_STAR_SCHEMA"
GROUP BY PRODUCT_NAME, CATEGORY, CUSTOMER_NAME, REGION, YEAR, MONTH
LIMIT 10;

-- Test 2: Sales by Product Category and Region
SELECT
CATEGORY,
REGION,
SUM(AMOUNT) AS TOTAL_SALES,
COUNT(*) AS TRANSACTION_COUNT
FROM "CAC_R_ORDERS_STAR_SCHEMA"
GROUP BY CATEGORY, REGION
ORDER BY TOTAL_SALES DESC;

-- Test 3: Time-based analysis
SELECT
YEAR,
QUARTER,
SUM(REVENUE) AS TOTAL_REVENUE,
SUM(DISCOUNT) AS TOTAL_DISCOUNT,
SUM(NET_AMOUNT) AS NET_REVENUE
FROM "CAC_R_ORDERS_STAR_SCHEMA"
GROUP BY YEAR, QUARTER
ORDER BY YEAR, QUARTER;

-- Test 4: Customer segment analysis
SELECT
SEGMENT,
COUNT(DISTINCT CUSTOMER_ID) AS CUSTOMER_COUNT,
SUM(AMOUNT) AS TOTAL_SALES,
AVG(AMOUNT) AS AVG_SALE_AMOUNT
FROM "CAC_R_ORDERS_STAR_SCHEMA"
GROUP BY SEGMENT;

-- Test 5: Top products by revenue
SELECT
PRODUCT_NAME,
CATEGORY,
SUM(REVENUE) AS TOTAL_REVENUE,
SUM(QUANTITY) AS UNITS_SOLD
FROM "CAC_R_ORDERS_STAR_SCHEMA"
GROUP BY PRODUCT_NAME, CATEGORY
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;