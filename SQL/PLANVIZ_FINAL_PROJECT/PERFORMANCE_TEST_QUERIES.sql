-- 5. Monitoring & Performance Tuning

--5_1_DIRECT_SQL - Join Performance Test
SELECT
    D.CALENDAR_DATE AS ORDER_DATE,
    C.CARRIER_NAME,
    SUM(O.AMOUNT) AS TOTAL_ORDER_VALUE
FROM "FACT_ORDERS" O
LEFT JOIN "DIM_DATE" D
    ON O.DATE_ID = D.DATE_ID
LEFT JOIN "DIM_CARRIER" C
    ON O.CARRIER_ID = C.CARRIER_ID
WHERE D.CALENDAR_DATE >= '2026-10-01'
  AND D.CALENDAR_DATE < '2026-11-01'
GROUP BY
    D.CALENDAR_DATE,
    C.CARRIER_NAME
ORDER BY
    D.CALENDAR_DATE,
    C.CARRIER_NAME;
    
--5_1_CALCULATION_VIEW - Performance Test
SELECT
    "ORDER_DATE",
    "CARRIER_NAME",
    SUM("ORDER_VALUE") AS "TOTAL_ORDER_VALUE"
FROM "CAC_R_DELIVERY_PERFORMANCE"
WHERE "ORDER_DATE" >= '2026-10-01'
  AND "ORDER_DATE" < '2026-11-01'
GROUP BY
    "ORDER_DATE",
    "CARRIER_NAME"
ORDER BY
    "ORDER_DATE",
    "CARRIER_NAME";

--5_2_Calculation View - WITHOUT_DATE_FILTER
SELECT
    "ORDER_DATE",
    SUM("ORDER_VALUE") AS "TOTAL_ORDER_VALUE"
FROM "CAC_R_DELIVERY_PERFORMANCE"
GROUP BY "ORDER_DATE"
ORDER BY "ORDER_DATE";

--5_2_Calculation View - WITH_DATE_FILTER
SELECT
    "ORDER_DATE",
    SUM("ORDER_VALUE") AS "TOTAL_ORDER_VALUE"
FROM "CAC_R_DELIVERY_PERFORMANCE"
WHERE "ORDER_DATE" >= DATE'2026-10-01'
  AND "ORDER_DATE" < DATE'2026-11-01'
GROUP BY "ORDER_DATE"
ORDER BY "ORDER_DATE";

-- M_EXPENSIVE_STATEMENTS - Monitoring Check
SELECT
    START_TIME,
    DURATION_MICROSEC / 1000 AS DURATION_MS,
    STATEMENT_STRING
FROM SYS.M_EXPENSIVE_STATEMENTS
ORDER BY START_TIME DESC
LIMIT 20;