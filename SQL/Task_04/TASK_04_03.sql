-- Test 1: View aggregated data
SELECT * FROM "CAC_I_ORDERS_AGGREGATED" ORDER BY TOTAL_SALES DESC;

-- Test 2: Further aggregation (should be fast due to pre-aggregation)
SELECT CATEGORY, SUM(TOTAL_SALES) AS CATEGORY_TOTAL
FROM "CAC_I_ORDERS_AGGREGATED"
GROUP BY CATEGORY;

-- Test 3: Calculate additional metrics
SELECT
CATEGORY,
DELIVERY_YEAR,
TOTAL_SALES,
TRANSACTION_COUNT,
CAST(TOTAL_SALES / TRANSACTION_COUNT as DECIMAL(10,2)) AS SALES_PER_TRANSACTION
FROM "CAC_I_ORDERS_AGGREGATED";