-- Load sample historical exchange rates.
-- Rates are illustrative, not official market rates.
-- The script can be executed multiple times without duplicates.

-- 1. Base currency: EUR to EUR
INSERT INTO EXCHANGE_RATES
    (SOURCE_CURRENCY, TARGET_CURRENCY, VALID_FROM, RATE)
SELECT
    'EUR', 'EUR', TO_DATE('2022-01-01'), 1.00000
FROM DUMMY
WHERE NOT EXISTS (
    SELECT 1
    FROM EXCHANGE_RATES
    WHERE SOURCE_CURRENCY = 'EUR'
      AND TARGET_CURRENCY = 'EUR'
      AND VALID_FROM = TO_DATE('2022-01-01')
);

-- 2. Monthly rates: EUR to USD, GBP and PLN
INSERT INTO EXCHANGE_RATES
    (SOURCE_CURRENCY, TARGET_CURRENCY, VALID_FROM, RATE)
SELECT
    'EUR' AS SOURCE_CURRENCY,
    C.TARGET_CURRENCY,
    ADD_MONTHS(
        TO_DATE('2022-01-01'),
        N.GENERATED_PERIOD_START
    ) AS VALID_FROM,
    CAST(
        CASE C.TARGET_CURRENCY
            WHEN 'USD' THEN 1.10 + MOD(N.GENERATED_PERIOD_START, 6) * 0.01
            WHEN 'GBP' THEN 0.83 + MOD(N.GENERATED_PERIOD_START, 5) * 0.01
            WHEN 'PLN' THEN 4.30 + MOD(N.GENERATED_PERIOD_START, 8) * 0.05
        END AS DECIMAL(15,5)
    ) AS RATE
FROM SERIES_GENERATE_INTEGER(1, 0, 54) AS N
CROSS JOIN (
    SELECT 'USD' AS TARGET_CURRENCY FROM DUMMY
    UNION ALL
    SELECT 'GBP' AS TARGET_CURRENCY FROM DUMMY
    UNION ALL
    SELECT 'PLN' AS TARGET_CURRENCY FROM DUMMY
) AS C
WHERE NOT EXISTS (
    SELECT 1
    FROM EXCHANGE_RATES E
    WHERE E.SOURCE_CURRENCY = 'EUR'
      AND E.TARGET_CURRENCY = C.TARGET_CURRENCY
      AND E.VALID_FROM = ADD_MONTHS(
          TO_DATE('2022-01-01'),
          N.GENERATED_PERIOD_START
      )
);