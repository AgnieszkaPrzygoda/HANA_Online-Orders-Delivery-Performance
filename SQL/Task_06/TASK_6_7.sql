-- Same data in different target currencies
SELECT
    EUR.ORDER_ID,
    EUR.LINE_ITEM_ID,
    EUR.AMOUNT AS ORIGINAL_EUR,
    EUR.CONVERTED_AMOUNT AS AMOUNT_EUR,
    USD.CONVERTED_AMOUNT AS AMOUNT_USD,
    USD.RATE AS USD_RATE
FROM "CV_SALES_MULTI_CURRENCY"
    (PLACEHOLDER."$$IP_TARGET_CURRENCY$$" => 'EUR') AS EUR
JOIN "CV_SALES_MULTI_CURRENCY"
    (PLACEHOLDER."$$IP_TARGET_CURRENCY$$" => 'USD') AS USD
    ON EUR.ORDER_ID = USD.ORDER_ID
    AND EUR.LINE_ITEM_ID = USD.LINE_ITEM_ID
ORDER BY EUR.ORDER_ID, EUR.LINE_ITEM_ID
LIMIT 10;


-- Verify currency conversion calculation
SELECT
    ORDER_ID,
    LINE_ITEM_ID,
    AMOUNT AS ORIGINAL_EUR,
    RATE AS USD_RATE,
    CONVERTED_AMOUNT AS ACTUAL_USD,
    ROUND(AMOUNT * RATE, 2) AS EXPECTED_USD,
    CASE
        WHEN CONVERTED_AMOUNT = ROUND(AMOUNT * RATE, 2)
        THEN 'CORRECT'
        ELSE 'INCORRECT'
    END AS VALIDATION_RESULT
FROM "CV_SALES_MULTI_CURRENCY"
    (PLACEHOLDER."$$IP_TARGET_CURRENCY$$" => 'USD')
ORDER BY ORDER_ID, LINE_ITEM_ID
LIMIT 10;


-- Multi-currency comparison report
