-- Test 1: Basic join output
SELECT * FROM "CAC_I_ORDERS_WITH_PRODUCTS" LIMIT 10;

-- Test 2: Aggregation by category
SELECT
CATEGORY,
COUNT(*) AS ORDERS_COUNT,
SUM(AMOUNT) AS TOTAL_SALES,
SUM(PROFIT_ESTIMATE) AS ESTIMATED_PROFIT
FROM "CAC_I_ORDERS_WITH_PRODUCTS"
GROUP BY CATEGORY;

-- Test 3: Top selling products
SELECT
PRODUCT_NAME,
SUM(QUANTITY) AS TOTAL_QUANTITY,
SUM(AMOUNT) AS TOTAL_REVENUE
FROM "CAC_I_ORDERS_WITH_PRODUCTS"
GROUP BY PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;